export function Ionicons({ name, size = 24, color = 'currentColor', style }: IconProps) {
  if (name === 'play') {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill={color}
        style={style}
        aria-hidden="true"
      >
        <polygon points="6 3 20 12 6 21 6 3" />
      </svg>
    );
  }
  // 'refresh' and anything else -> the circular-arrows glyph.
  return strokeIcon({ name: 'refresh-cw', size, color, style });
}
Ionicons.glyphMap = { play: 0, refresh: 0 } as const;

